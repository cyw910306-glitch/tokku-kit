// 카카오 공식 테마 가이드 26.8.0 샘플의 Images 폴더(66장 이름·크기)와 scripts/template.css 를 읽어
// public/engine/spec.js 와 tests/fixtures/ref-images.json 을 만든다. 손으로 옮겨 적지 않는다. (규격 갱신 때 관리자만)
// usage: node scripts/gen-spec.mjs <공식 샘플 Images 폴더>
// 공식 샘플 그림은 카카오 캐릭터라 저장소에 넣지 않는다 (ref/ 는 .gitignore).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const IMG_DIR = process.argv[2];
if (!IMG_DIR) { console.error('usage: node scripts/gen-spec.mjs <official sample Images dir>'); process.exit(2); }
const TEMPLATE = join(ROOT, 'scripts', 'template.css');
const OUT = join(ROOT, 'public', 'engine', 'spec.js');
const MANIFEST = join(ROOT, 'tests', 'fixtures', 'ref-images.json');

// PNG IHDR: 시그니처 8 + 길이 4 + 'IHDR' 4 다음 width, height (big-endian u32)
function pngSize(path) {
  const b = readFileSync(path);
  if (b.toString('latin1', 12, 16) !== 'IHDR') throw new Error(`not a PNG: ${path}`);
  return [b.readUInt32BE(16), b.readUInt32BE(20)];
}

const images = readdirSync(IMG_DIR).filter(f => f.endsWith('.png')).sort()
  .map(name => { const [w, h] = pngSize(join(IMG_DIR, name)); return { name, w, h }; });
if (images.length !== 66) throw new Error(`expected 66 images, got ${images.length}`);

// 템플릿 견본 색 -> Palette 토큰 (accentDark 는 css.js 가 accent 에서 파생). #FFFFFF 는 그대로 둔다.
const COLOR = {
  '#FFF6EE': 'bg', '#FFF0F5': 'tabBg', '#4A3440': 'text', '#3A2A33': 'text',
  '#8A6878': 'muted', '#8C6878': 'muted', '#76566A': 'muted', '#6B4A5A': 'muted', '#7A5A68': 'muted',
  '#B23A64': 'accent', '#8F2D50': 'accentDark', '#E8789A': 'line',
  '#F6E1E9': 'sendFill', '#EBCAD7': 'sendSel', '#F7C9DA': 'sendFill', '#FFE3EC': 'sendFill',
  '#FFEFF4': 'keypad',
};

let css = readFileSync(TEMPLATE, 'utf8')
  .replace(/\/\*[\s\S]*?\*\//g, '')                       // 주석 제거
  .replace(/MessageCellStyle-Send\n\{[\s\S]*?\n\}/, '{{bubbleSend}}')
  .replace(/MessageCellStyle-Receive\n\{[\s\S]*?\n\}/, '{{bubbleReceive}}')
  .replace(/(-kakaotalk-theme-name: )'[^']*'/, "$1'{{name}}'")
  .replace(/(-kakaotalk-theme-url: )'[^']*'/, "$1'https://tokku-kit.vercel.app'")
  .replace(/(-kakaotalk-author-name: )'[^']*'/, "$1'Tokku Kit'")
  .replace(/(-kakaotalk-theme-id: )'[^']*'/, "$1'{{id}}'")
  .replace(/#[0-9A-Fa-f]{6}\b/g, c => {
    const u = c.toUpperCase();
    if (u === '#FFFFFF') return u;
    if (!COLOR[u]) throw new Error(`unmapped color ${c}`);
    return `{{${COLOR[u]}}}`;
  })
  .replace(/[ \t]+$/gm, '').replace(/\n\n+(\})/g, '\n$1').replace(/\n{3,}/g, '\n\n').trim();
css = '/* Tokku Kit: KakaoTalk iOS theme (.ktheme) maker. base: theme guide 26.8.0 */\n\n' + css + '\n';
if (/\u2014/.test(css)) throw new Error('em dash in template');

const out = `// GENERATED by scripts/gen-spec.mjs from the official sample Images + scripts/template.css. Do not edit.
export const IMAGES = ${JSON.stringify(images)};
export const CSS_TEMPLATE = ${JSON.stringify(css)};
`;
writeFileSync(OUT, out);
writeFileSync(MANIFEST, JSON.stringify(images, null, 0).replace(/\},\{/g, '},\n{') + '\n');
console.log(`spec.js: ${images.length} images, template ${css.length} chars, tokens ${[...new Set(css.match(/\{\{\w+\}\}/g))].join(' ')}`);
